import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { doc, getDoc, getDocs, collection, setDoc } from 'firebase/firestore';
import { leaderboardFixture } from './leaderboard-fixture.mjs';
const f = await leaderboardFixture();
let groups = 0;
const pass = () => groups++;
const deny = (p, code) => assert.rejects(p, e => e.code === 'functions/' + code);
const cmd = (action, revision, extra = {}) => ({ eventId: f.eventId, sessionId: f.sessionId, requestId: randomUUID(), expectedRevision: revision, action, ...extra });
const publish = async (p) => f.call('controlInterimResults', cmd('publish', p.sessionRevision, { throughRoundId: p.throughRoundId, sourceFingerprint: p.sourceFingerprint }));
try {
    let p = await f.preview();
    assert.deepEqual(p.rows.map(r => r.rank), [1, 2, 2, 3]);
    assert.deepEqual(p.rows.map(r => r.halfPoints), [40, 35, 35, 30]);
    assert(!p.rows.some(r => r.teamName.includes('Cancelled')));
    assert(!(await f.publicState()).interimResults);
    pass();
    await deny(f.preview('r3'), 'failed-precondition');
    await deny(f.preview('foreign'), 'invalid-argument');
    await deny(f.call('previewInterimResults', { eventId: 'foreign', sessionId: f.sessionId, throughRoundId: 'r2' }), 'failed-precondition');
    await deny(f.anonymous.call('previewInterimResults', { eventId: f.eventId, sessionId: f.sessionId, throughRoundId: 'r2', key: 'referee', token: 'management' }), 'unauthenticated');
    await assert.rejects(getDoc(doc(f.anonymous.store, 'sessions', f.sessionId)), e => e.code === 'permission-denied');
    await assert.rejects(getDocs(collection(f.anonymous.store, 'publicSessions')), e => e.code === 'permission-denied');
    pass();
    const grant = await f.referee();
    await deny(f.anonymous.call('previewInterimResults', { ...grant, sessionId: f.sessionId, throughRoundId: 'r2' }), 'unauthenticated');
    await deny(f.anonymous.call('controlInterimResults', { ...cmd('publish', p.sessionRevision, { throughRoundId: 'r2', sourceFingerprint: p.sourceFingerprint }), ...grant }), 'unauthenticated');
    await f.authAdmin.setCustomUserClaims(f.moderator.uid, { role: 'user' });
    await deny(f.preview(), 'permission-denied');
    await f.authAdmin.setCustomUserClaims(f.moderator.uid, { role: 'moderator' });
    pass();
    await f.score(0, 1, 41);
    await deny(publish(p), 'aborted');
    p = await f.preview();
    const request = cmd('publish', p.sessionRevision, { throughRoundId: p.throughRoundId, sourceFingerprint: p.sourceFingerprint });
    const published = await f.call('controlInterimResults', request);
    const first = await f.publicState();
    assert(first.interimResults);
    assert(!/PRIVATE|actorUid|contactEmail|sourceFingerprint|snapshotId/.test(JSON.stringify(first)));
    assert.equal(first.interimResults.rows[0].halfPoints, 61);
    pass();
    await f.score(0, 1, 43);
    assert.deepEqual(await f.publicState(), first);
    await f.db.doc(`events/${f.eventId}/registrations/${f.teamIds[0]}`).update({ teamName: 'Renamed Alfa', revision: 2 });
    assert.deepEqual(await f.publicState(), first);
    pass();
    assert.deepEqual(await f.call('controlInterimResults', request), published);
    await deny(f.call('controlInterimResults', { ...request, sourceFingerprint: 'changed' }), 'already-exists');
    await assert.rejects(setDoc(doc(f.admin.store, 'publicSessions', f.sessionId), { interimResults: { rows: [] } }), e => e.code === 'permission-denied');
    await assert.rejects(getDoc(doc(f.anonymous.store, 'sessions', f.sessionId, 'interimVersions', first.interimResults.versionId)), e => e.code === 'permission-denied');
    await assert.rejects(getDoc(doc(f.anonymous.store, 'events', f.eventId, 'scores', 'any')), e => e.code === 'permission-denied');
    pass();
    const revision = (await f.session()).revision;
    const concurrent = await Promise.allSettled([f.call('controlInterimResults', cmd('hide', revision)), f.admin.call('controlInterimResults', cmd('hide', revision))]);
    assert.equal(concurrent.filter(x => x.status === 'fulfilled').length, 1);
    assert(!(await f.publicState()).interimResults);
    await f.call('controlInterimResults', request);
    assert(!(await f.publicState()).interimResults, 'Completed publish retry resurrected results');
    pass();
    p = await f.preview();
    await f.db.doc(`events/${f.eventId}/registrations/${f.teamIds[1]}`).update({ status: 'cancelled' });
    await deny(publish(p), 'aborted');
    const scoreDoc = (await f.db.collection(`events/${f.eventId}/scores`).where('teamId', '==', f.teamIds[2]).where('roundId', '==', 'r1').get()).docs[0];
    await scoreDoc.ref.update({ halfPoints: null, revision: 2 });
    p = await f.preview();
    assert(!p.complete);
    assert(p.missing.some(m => m.teamName === 'Gama' && m.roundId === 'r1'));
    await deny(publish(p), 'failed-precondition');
    await scoreDoc.ref.update({ halfPoints: 0, revision: 3 });
    pass();
    // Media/reveal transitions reset generation and cannot restore a selected answer.
    let s = await f.session();
    await f.call('revealAnswer', { sessionId: f.sessionId, expectedRevision: s.revision });
    assert((await f.publicState()).revealedAnswer);
    p = await f.preview();
    await publish(p);
    assert(!(await f.publicState()).revealedAnswer);
    s = await f.session();
    await deny(f.call('reportMediaPlayback', { sessionId: f.sessionId, mediaGeneration: s.mediaGeneration - 1, playbackState: 'playing' }), 'aborted');
    await f.call('controlInterimResults', cmd('hide', s.revision));
    s = await f.session();
    assert.equal(s.currentSlidePosition, 1);
    assert.equal(s.answerRevealed, false);
    assert.equal(s.mediaPlaybackState, 'idle');
    assert(!(await f.publicState()).revealedAnswer);
    pass();
    p = await f.preview();
    await f.db.doc('events/' + f.eventId + '/registrations/' + f.teamIds[0]).update({ teamName: 'Another name', revision: 3 });
    await deny(publish(p), 'aborted');
    p = await f.preview();
    await publish(p);
    p = await f.preview();
    const race = await Promise.allSettled([publish(p), f.admin.call('controlInterimResults', cmd('hide', p.sessionRevision))]);
    assert.equal(race.filter(x => x.status === 'fulfilled').length, 1);
    assert.equal(race.find(x => x.status === 'rejected').reason.code, 'functions/aborted');
    s = await f.session();
    if (s.interimResults)
        await f.call('controlInterimResults', cmd('hide', s.revision));
    s = await f.session();
    await f.call('goToSlide', { sessionId: f.sessionId, expectedRevision: s.revision, position: 2 });
    s = await f.session();
    await f.call('playMedia', { sessionId: f.sessionId, expectedRevision: s.revision });
    s = await f.session();
    const playingGeneration = s.mediaGeneration;
    p = await f.preview();
    await publish(p);
    s = await f.session();
    assert(s.mediaGeneration > playingGeneration);
    assert.equal(s.mediaPlaybackState, 'idle');
    await f.call('controlInterimResults', cmd('hide', s.revision));
    s = await f.session();
    assert.equal(s.currentSlidePosition, 2);
    assert.equal(s.mediaCommand, 'idle');
    await deny(f.call('reportMediaPlayback', { sessionId: f.sessionId, mediaGeneration: playingGeneration, playbackState: 'playing' }), 'aborted');
    pass();
    p = await f.preview();
    await publish(p);
    s = await f.session();
    await f.call('endLiveSession', { sessionId: f.sessionId, expectedRevision: s.revision });
    assert.equal((await f.publicState()).status, 'ended');
    assert(!(await f.publicState()).interimResults);
    await deny(publish(p), 'failed-precondition');
    pass();
    const second = await leaderboardFixture();
    try {
        const q = await second.preview();
        await deny(second.call('previewInterimResults', { eventId: f.eventId, sessionId: second.sessionId, throughRoundId: 'r2' }), 'failed-precondition');
        await deny(second.call('controlInterimResults', { eventId: f.eventId, sessionId: second.sessionId, action: 'publish', requestId: randomUUID(), expectedRevision: q.sessionRevision, throughRoundId: 'r2', sourceFingerprint: q.sourceFingerprint }), 'failed-precondition');
        await second.call('controlInterimResults', { eventId: second.eventId, sessionId: second.sessionId, action: 'publish', requestId: randomUUID(), expectedRevision: q.sessionRevision, throughRoundId: 'r2', sourceFingerprint: q.sourceFingerprint });
        const e = (await second.db.doc('events/' + second.eventId).get()).data();
        await second.admin.call('cancelEvent', { eventId: second.eventId, expectedRevision: e.revision });
        assert.equal((await second.publicState()).status, 'ended');
        assert(!(await second.publicState()).interimResults);
        await deny(second.preview(), 'failed-precondition');
        const cancelled = (await second.db.doc('events/' + second.eventId).get()).data();
        await second.admin.call('archiveEvent', { eventId: second.eventId, expectedRevision: cancelled.revision });
        await deny(second.preview(), 'failed-precondition');
        assert.equal((await second.publicState()).status, 'ended');
        assert(!(await second.publicState()).interimResults);
    }
    finally {
        await second.close();
    }
    pass();
    console.log(`Leaderboard emulator contracts: ${groups} groups PASS.`);
}
finally {
    await f.close();
}
