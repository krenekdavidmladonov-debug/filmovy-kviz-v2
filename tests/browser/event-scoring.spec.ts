import { seedEmulatorMembership } from '../../functions/src/dev/seed-membership.js';
import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';

// Create an ephemeral synthetic staff account; never store a test password in Git.
let loginEmail: string, loginPassword: string;
let cleanup: (() => Promise<void>) | undefined;
test.beforeAll(async () => {
  const projectId = process.env.GCLOUD_PROJECT;
  if (projectId !== 'demo-filmovy-kviz-v2' || !/^(127\.0\.0\.1|localhost):9099$/u.test(process.env.FIREBASE_AUTH_EMULATOR_HOST ?? '')) {
    throw new Error('Scoring browser fixtures require the local demo Auth emulator.');
  }
  const require = createRequire(new URL('../../functions/package.json', import.meta.url));
  const sdk = require('firebase-admin/app') as { initializeApp(options: { projectId: string }, name: string): object; deleteApp(app: object): Promise<void> };
  const app = sdk.initializeApp({ projectId }, 'scoring-browser-' + randomUUID());
  const authSdk = require('firebase-admin/auth') as { getAuth(app: object): {
    createUser(data: { email: string; password: string }): Promise<{ uid: string }>;
    setCustomUserClaims(uid: string, claims: { role: string }): Promise<void>;
    deleteUser(uid: string): Promise<void>;
  } };
  const auth = authSdk.getAuth(app);
  loginEmail = 'score-browser-' + randomUUID() + '@example.test'; loginPassword = randomUUID();
  const user = await auth.createUser({ email: loginEmail, password: loginPassword });
  cleanup = async () => { await auth.deleteUser(user.uid); await sdk.deleteApp(app); };
  await auth.setCustomUserClaims(user.uid, { role: 'admin' }); await seedEmulatorMembership(user.uid, 'admin');
});
test.afterAll(async () => { await cleanup?.(); });

test('explicit scoring, reload, reason, two views, history, lost response and navigation', async ({ page, context }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/admin/login');
  await page.getByLabel('E-mail').fill(loginEmail);
  await page.getByLabel('Heslo').fill(loginPassword);
  await page.getByRole('button', { name: 'Přihlásit se' }).click();
  await expect(page).toHaveURL(/\/admin$/u);
  await page.goto('/admin/events/new');
  await page.getByLabel('Název akce').fill('Synthetic scoring browser');
  await page.getByLabel('Datum a čas').fill('2031-11-20T19:00');
  await page.getByLabel('Místo', { exact: true }).fill('Synthetic venue');
  await page.getByLabel('Veřejné upřesnění místa').fill('Synthetic location');
  await page.getByRole('button', { name: 'Vytvořit akci' }).click();
  await expect(page).toHaveURL(/\/admin\/events\/[^/]+$/u);
  await page.getByRole('button', { name: '+ Přidat tým', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Název týmu').fill('Bodovací tým');
  await page.getByRole('dialog').getByRole('button', { name: 'Přidat tým', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Kvíz', exact: true }).selectOption('preflight-ready-e2e');
  await page.getByRole('button', { name: 'Zkontrolovat a připravit', exact: true }).click();
  await expect(page.getByText('Kvíz byl zkontrolován a připraven.')).toBeVisible();
  await page.getByRole('link', { name: 'Otevřít bodování' }).click();
  const url = page.url();
  const row = page.getByRole('region', { name: 'Bodovací tým', exact: true });
  const points = page.getByLabel('Body — Bodovací tým', { exact: true });
  await expect(row).toContainText('Nezadáno');
  await points.fill('2,5');
  await expect(row).toContainText('Změněno · neuloženo');
  await expect(row).toContainText('revize 0');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('Uložení potvrzeno serverem.');
  await page.reload();
  await expect(points).toHaveValue('2,5');
  await points.fill('3.5');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('Doplňte stručný důvod');
  await page.getByLabel('Důvod opravy — Bodovací tým').fill('Přepočet archu');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('revize 2');
  const second = await context.newPage(); await second.goto(url);
  const secondRow = second.getByRole('region', { name: 'Bodovací tým', exact: true });
  await second.getByLabel('Body — Bodovací tým', { exact: true }).fill('5');
  await points.fill('4');
  await page.getByLabel('Důvod opravy — Bodovací tým').fill('Druhý přepočet');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('revize 3');
  await expect(secondRow).toContainText('Aktuálně uloženo: 4 bodů');
  await expect(second.getByLabel('Body — Bodovací tým', { exact: true })).toHaveValue('5');
  await expect(secondRow.getByRole('button', { name: 'Uložit', exact: true })).toBeDisabled();
  await secondRow.getByRole('button', { name: 'Připravit opravu aktuální revize' }).click();
  await second.getByLabel('Důvod opravy — Bodovací tým').fill('Rozhodnutí po konfliktu');
  await secondRow.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(secondRow).toContainText('revize 4');
  await row.getByRole('button', { name: 'Historie změn' }).click();
  await expect(row.locator('li')).toHaveCount(4);
  await expect(row).toContainText('Přepočet archu');
  await expect(row).toContainText('Rozhodnutí po konfliktu');
  await second.close();
  // Lost response after committed request must retry the same operation even after the live update.
  await points.fill('6,5'); await page.getByLabel('Důvod opravy — Bodovací tým').fill('Ověření opakování');
  let dropped = false;
  await page.route('**/saveEventScore', async route => {
    if (!dropped) { dropped = true; await route.fetch(); await route.abort('failed'); } else await route.continue();
  });
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('Uložení se nepodařilo potvrdit');
  await expect(points).toHaveValue('6,5');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('Uložení potvrzeno serverem.');
  await expect(row).toContainText('revize 5');
  await points.fill('');
  await row.getByRole('button', { name: 'Uložit', exact: true }).click();
  await expect(row).toContainText('Zadejte nezáporné body');
  await expect(row).toContainText('6,5 bodů');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('link', { name: 'Zpět na detail akce' }).click();
  await expect(page).toHaveURL(url);
  await expect(points).toHaveValue('');
  await page.getByLabel('Důvod opravy — Bodovací tým').fill('Zápis patřil jinému týmu');
  page.once('dialog', dialog => dialog.accept());
  await row.getByRole('button', { name: 'Vrátit na nezadáno' }).click();
  await expect(row).toContainText('Nezadáno');
  await expect(row).toContainText('revize 6');
  await row.getByRole('button', { name: 'Historie změn' }).click();
  await expect(row.locator('li')).toHaveCount(6);
  mkdirSync('.local-data/event-scoring/screenshots', { recursive: true });
  await page.screenshot({ path: '.local-data/event-scoring/screenshots/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.local-data/event-scoring/screenshots/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
