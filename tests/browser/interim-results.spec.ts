import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { leaderboardFixture } from '../e2e/leaderboard-fixture.mjs';
let fixture: Awaited<ReturnType<typeof leaderboardFixture>>;
test.beforeAll(async () => { fixture = await leaderboardFixture(12); });
test.afterAll(async () => { await fixture?.close(); });
test('moderator explicitly previews, publishes, updates and hides interim results on the existing projector', async ({ page, context, browser }) => {
    await context.route('**/*', r => ['127.0.0.1', 'localhost'].includes(new URL(r.request().url()).hostname) ? r.continue() : r.abort());
    await page.goto('/admin/login');
    await page.getByLabel('E-mail').fill(fixture.login.email);
    await page.getByLabel('Heslo').fill(fixture.login.password);
    await page.getByRole('button', { name: 'Přihlásit se' }).click();
    await expect(page).toHaveURL(/\/admin$/);
    await page.goto('/admin/events/' + fixture.eventId);
    await page.getByRole('button', { name: 'Otevřít moderování akce' }).click();
    await expect(page).toHaveURL('/admin/live/' + fixture.sessionId);
    const projectorContext = await browser.newContext({ baseURL: 'http://127.0.0.1:5194', viewport: { width: 1920, height: 1080 } });
    await projectorContext.route('**/*', r => ['127.0.0.1', 'localhost'].includes(new URL(r.request().url()).hostname) ? r.continue() : r.abort());
    const projector = await projectorContext.newPage();
    await projector.goto('/projector/' + fixture.sessionId);
    await expect(projector.getByText('Synthetic prompt', { exact: true })).toBeVisible();
    const panel = page.getByRole('region', { name: 'Ovládání průběžných výsledků' });
    const published = projector.getByRole('article', { name: 'Průběžné výsledky' });
    await panel.getByLabel('Výsledky po kole').selectOption('r2');
    await expect(panel.getByLabel('Výsledky po kole').locator('option')).toHaveCount(2);
    await panel.getByRole('button', { name: 'Načíst náhled výsledků' }).click();
    await expect(panel.getByRole('heading', { name: 'Interní náhled — zatím nezveřejněno' })).toBeVisible();
    await expect(published).toHaveCount(0);
    expect((await fixture.publicState()).interimResults).toBeUndefined();
    // A forged transport payload must never become publication authority.
    await projector.evaluate(({ sessionId }) => { const c = new BroadcastChannel('filmovy-kviz-projector-' + sessionId); c.postMessage({ type: 'public-state', state: { sessionId, revision: 99, interimResults: { versionId: 'a'.repeat(64), roundNumber: 2, page: 0, pageCount: 1, rows: [{ rank: 1, teamName: 'UNPUBLISHED INJECTION', halfPoints: 999 }] } } }); c.close(); }, { sessionId: fixture.sessionId });
    await expect(projector.getByText('UNPUBLISHED INJECTION')).toHaveCount(0);
    await panel.getByRole('button', { name: 'Zobrazit výsledky', exact: true }).click();
    await expect(published).toBeVisible();
    await expect(page.getByRole('button', { name: 'Ukončit kvíz', exact: true })).toBeEnabled();
    await expect(published.getByRole('heading')).toHaveText('Průběžné výsledky po 2. kole');
    const rows = published.locator('tbody tr');
    await expect(rows).toHaveCount(8);
    await expect(rows.nth(0)).toContainText('Alfa');
    await expect(rows.nth(1)).toContainText('17,5');
    await expect(rows.nth(1).locator('td').first()).toHaveText('2.');
    await expect(rows.nth(2).locator('td').first()).toHaveText('2.');
    await expect(rows.nth(3).locator('td').first()).toHaveText('3.');
    mkdirSync('.local-data/leaderboard/screenshots', { recursive: true });
    for (const viewport of [{ width: 1920, height: 1080 }, { width: 1280, height: 720 }]) {
        await projector.setViewportSize(viewport);
        const last = await rows.last().boundingBox();
        expect(last !== null && last.y + last.height <= viewport.height).toBe(true);
        expect(await projector.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await projector.screenshot({ path: '.local-data/leaderboard/screenshots/projector-' + viewport.width + '.png' });
    }
    await panel.getByRole('button', { name: 'Další stránka projektoru' }).click();
    await expect(rows).toHaveCount(4);
    await expect(published).toContainText('Tým 12');
    await expect(published).toContainText('Strana 2 z 2');
    await panel.getByRole('button', { name: 'Předchozí stránka projektoru' }).click();
    await expect(rows).toHaveCount(8);
    const before = await fixture.publicState();
    const credential = await fixture.referee();
    const refContext = await browser.newContext({ baseURL: 'http://127.0.0.1:5194', viewport: { width: 390, height: 844 } });
    await refContext.route('**/*', r => ['127.0.0.1', 'localhost'].includes(new URL(r.request().url()).hostname) ? r.continue() : r.abort());
    const referee = await refContext.newPage();
    await referee.goto('/referee/' + credential.eventId + '#access=' + credential.accessId + '&key=' + credential.key);
    await expect(referee.getByLabel('Body — Alfa', { exact: true })).toBeVisible();
    await referee.getByRole('combobox').selectOption('r2');
    await referee.getByLabel('Body — Alfa', { exact: true }).fill('25,5');
    await referee.getByLabel('Důvod opravy — Alfa').fill('Synthetic referee correction');
    await referee.getByRole('region', { name: 'Alfa', exact: true }).getByRole('button', { name: 'Uložit', exact: true }).click();
    await expect(referee.getByRole('region', { name: 'Alfa', exact: true })).toContainText('Uložení potvrzeno serverem.');
    expect(await fixture.publicState()).toEqual(before);
    await expect(rows.nth(0)).toContainText('20');
    await refContext.close();
    await panel.getByRole('button', { name: 'Načíst náhled výsledků' }).click();
    await expect(panel.getByRole('region', { name: 'Interní náhled výsledků' })).toContainText('35,5');
    await expect(rows.nth(0)).not.toContainText('35,5');
    await panel.getByRole('button', { name: 'Aktualizovat zobrazené výsledky' }).click();
    await expect(rows.nth(0)).toContainText('35,5');
    const latest = await fixture.publicState();
    await projector.evaluate(({ old, sessionId }) => { const c = new BroadcastChannel('filmovy-kviz-projector-' + sessionId); c.postMessage({ type: 'public-state', state: old }); c.postMessage({ type: 'public-state', state: { ...old, sessionId: 'foreign', revision: 999 } }); c.close(); }, { old: before, sessionId: fixture.sessionId });
    expect((latest.interimResults as {
        versionId: string;
    }).versionId !== (before.interimResults as {
        versionId: string;
    }).versionId).toBe(true);
    await expect(rows.nth(0)).toContainText('35,5');
    await page.setViewportSize({ width: 768, height: 900 });
    await expect(panel.getByRole('button', { name: 'Skrýt výsledky a vrátit prezentaci' })).toBeVisible();
    expect(await panel.evaluate(e => e.getBoundingClientRect().width <= innerWidth)).toBe(true);
    await page.screenshot({ path: '.local-data/leaderboard/screenshots/moderator-768.png' });
    await panel.getByRole('button', { name: 'Skrýt výsledky a vrátit prezentaci' }).click();
    await expect(published).toHaveCount(0);
    await projector.reload();
    await expect(projector.getByText('Synthetic prompt', { exact: true })).toBeVisible();
    await expect(published).toHaveCount(0);
    await expect(projector.getByText('PRIVATE ANSWER SENTINEL', { exact: true })).toHaveCount(0);
    expect((await fixture.session()).currentSlidePosition).toBe(1);
    expect((await fixture.session()).mediaPlaybackState).toBe('idle');
    expect((await fixture.publicState()).interimResults).toBeUndefined();
    await expect(projector.locator('audio,video,iframe')).toHaveCount(0);
    // Cached data cannot restore an old table during disconnect/reconnect.
    await panel.getByRole('button', { name: 'Načíst náhled výsledků' }).click();
    await panel.getByRole('button', { name: 'Zobrazit výsledky', exact: true }).click();
    await expect(published).toBeVisible();
    await expect(page.getByRole('button', { name: 'Ukončit kvíz', exact: true })).toBeEnabled();
    await projectorContext.setOffline(true);
    await expect(projector.getByText('Projektor není připojen', { exact: true })).toBeVisible();
    await panel.getByRole('button', { name: 'Skrýt výsledky a vrátit prezentaci' }).click();
    await expect.poll(async () => (await fixture.publicState()).interimResults).toBeUndefined();
    await projectorContext.setOffline(false);
    await expect(projector.getByText('Synthetic prompt', { exact: true })).toBeVisible();
    await expect(published).toHaveCount(0);
    await projectorContext.close();
});
